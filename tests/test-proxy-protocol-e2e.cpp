/*
 * test-proxy-protocol-e2e.cpp — Story 2.10 AC #1 #2 #3 #5.
 *
 * E2E driver for PROXY-protocol v1/v2 client-IP propagation through the
 * CF Worker → nginx → teleproxy server chain.  In CI the "CF Worker" and
 * "nginx" are replaced by a minimal C++ framing shim that injects the
 * PROXY-protocol header directly onto the upstream TCP connection.
 *
 * Compile (Linux, standalone — no Qt required for the shim driver):
 *   g++ -std=c++17 -O2 -o test-proxy-protocol-e2e \
 *       test-proxy-protocol-e2e.cpp -lpthread
 *
 * Usage:
 *   ./test-proxy-protocol-e2e --version v1 [--no-cdn] [--server-port 13129]
 *                              [--stats-port 8889]
 *                              [--binary PATH/TO/mtproto-proxy]
 *                              [--aes-pwd PATH] [--secret HEX]
 *
 * Exit codes:
 *   0  all assertions passed
 *   1  assertion failure (details on stderr)
 *   2  server launch or connectivity failure
 *
 * Story 2.10 §Sandbox-vs-prod caveat: this driver uses sandbox credentials
 * generated by gen-sandbox-secrets.sh.  Never pass production credentials.
 */

