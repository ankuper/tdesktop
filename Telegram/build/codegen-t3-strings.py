#!/usr/bin/env python3
"""
codegen-t3-strings.py — Type3 UI-string code generator.

Reads teleproto3/spec/ux-strings.yaml, validates each key against the
seven-token ban list, and emits t3lang::lng_* inline accessor functions into
tdesktop/Telegram/SourceFiles/lang/lang_keys.h between the
<type3-strings:begin> / <type3-strings:end> sentinel comments.

Invoked by CMake (add_custom_target lang_keys_t3) before compiling lang_keys.cpp.
On success writes a stamp file to signal CMake the step is current.
Fail: non-zero exit code + diagnostic message (blocks the build).

Design constraints (story 2.6 Dev Notes §codegen-hook-contract):
  - Reproducible: same input bytes → same output bytes.  No timestamps in emitted code.
  - Four locales MUST be present for every key: en, ru, fa, zh.
  - Seven banned tokens must be absent from every locale value.
  - Exactly the three Type3 keys are looked up:
      ui.tier3-toast, ui.tier3-action-switch, ui.secure-storage-unavailable
"""

import argparse
import re
import sys
from pathlib import Path

# ── Constants ───────────────────────────────────────────────────────────────

REQUIRED_LOCALES = ("en", "ru", "fa", "zh")

# (story 1.4 §AR-C1 / epic-2-style-guide §4) — seven literal banned tokens.
BANNED_TOKENS = [
    "proxy", "прокси", "پروکسی", "代理", "proxy-server", "bypass", "censorship",
]

# Keys to extract from ux-strings.yaml, in emission order.
# Maps: yaml-key → t3lang function name.
T3_KEYS = [
    ("ui.tier3-toast",               "lng_t3_tier3_toast"),
    ("ui.tier3-action-switch",       "lng_t3_tier3_action_switch"),
    ("ui.secure-storage-unavailable","lng_t3_secure_storage_unavailable"),
]

SENTINEL_BEGIN = "// <type3-strings:begin>"
SENTINEL_END   = "// <type3-strings:end>"

# ── YAML parsing (stdlib only — no PyYAML dependency in the build) ───────────

def parse_ux_strings(yaml_path: Path) -> dict:
    """
    Minimal hand-rolled parser for the ux-strings.yaml format.
    Returns dict[key] -> dict[locale] -> value string.
    Assumes the file follows the canonical schema (spec_version, strings: map).
    """
    text = yaml_path.read_text(encoding="utf-8")
    result = {}

    # Locate the "strings:" section.
    m = re.search(r"^strings:\s*$", text, re.MULTILINE)
    if not m:
        raise ValueError("ux-strings.yaml: missing 'strings:' map")

    strings_block = text[m.end():]

    # State machine: top-level key followed by locale sub-keys.
    current_key = None
    for line in strings_block.splitlines():
        # Skip blank lines and comment lines.
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue

        # Top-level key (two-space indent or none, ends with ':').
        top = re.match(r"^  (\S.*?):\s*$", line)
        if top:
            current_key = top.group(1)
            result[current_key] = {}
            continue

        # Locale sub-key (four-space indent, e.g. "    en: \"...\"").
        if current_key is not None:
            locale = re.match(r"^    ([a-z]{2}):\s+[\"']?(.*?)[\"']?\s*$", line)
            if locale:
                lang_code = locale.group(1)
                value = locale.group(2)
                # Strip surrounding quotes if present.
                value = value.strip('"\'')
                result[current_key][lang_code] = value

    return result


# ── Ban-list check ────────────────────────────────────────────────────────────

def check_ban_list(key: str, locale: str, value: str) -> None:
    """Fail the build if any banned token appears in the value."""
    value_lower = value.lower()
    for token in BANNED_TOKENS:
        if token.lower() in value_lower:
            sys.exit(
                f"BAN-LIST VIOLATION: key '{key}' locale '{locale}' contains "
                f"banned token '{token}'.\n"
                f"  Value: {value!r}\n"
                f"Edit ux-strings.yaml to remove the banned term."
            )


# ── Code emission ─────────────────────────────────────────────────────────────

def emit_section(strings: dict) -> str:
    """
    Produce the Type3 section content to insert between the sentinels.
    Output is deterministic: fixed order, no timestamps.
    """
    lines = [
        "// Generated by codegen-t3-strings.py from teleproto3/spec/ux-strings.yaml.",
        "// DO NOT edit this section manually — edit ux-strings.yaml and re-run codegen.",
        "// Append-only: story 2.6 owns this section; host-app strings above are out of scope.",
        "//",
        "// Ban-list: none of the string values below contain the seven banned tokens",
        "// (proxy / прокси / پروکسی / 代理 / proxy-server / bypass / censorship).",
        "namespace t3lang {",
        "",
    ]

    comments = {
        "ui.tier3-toast":               "// ui.tier3-toast (AC#3) — non-modal toast body on tier-3 halt.",
        "ui.tier3-action-switch":       "// ui.tier3-action-switch (AC#3) — single tappable action label on tier-3 toast.",
        "ui.secure-storage-unavailable":"// ui.secure-storage-unavailable (story 2.4 PREREQUISITE via story 2.6) — startup warning.",
    }

    for (yaml_key, fn_name) in T3_KEYS:
        entry = strings.get(yaml_key)
        if entry is None:
            sys.exit(
                f"codegen-t3-strings: key '{yaml_key}' not found in ux-strings.yaml.\n"
                f"Add the key and its en/ru/fa/zh values, then re-run."
            )
        for locale in REQUIRED_LOCALES:
            if locale not in entry:
                sys.exit(
                    f"codegen-t3-strings: key '{yaml_key}' is missing locale '{locale}'.\n"
                    f"Add all four locales (en/ru/fa/zh) to ux-strings.yaml."
                )
            check_ban_list(yaml_key, locale, entry[locale])

        # Emit comment + inline accessor (en locale is the scaffold value).
        en_value = entry["en"].replace('"', '\\"')
        comment = comments.get(yaml_key, f"// {yaml_key}")
        lines += [
            comment,
            f"[[nodiscard]] inline QString {fn_name}() {{",
            f"    // TODO(codegen): replace with locale-aware lookup; en value is authoritative.",
            f'    return u"{en_value}"_q;',
            f"}}",
            "",
        ]

    lines += ["} // namespace t3lang"]
    return "\n".join(lines)


# ── lang_keys.h patching ──────────────────────────────────────────────────────

def patch_lang_keys(header_path: Path, new_section: str) -> bool:
    """
    Replace the content between <type3-strings:begin> and <type3-strings:end>.
    Returns True if the file was modified, False if already up-to-date.
    """
    text = header_path.read_text(encoding="utf-8")

    begin_idx = text.find(SENTINEL_BEGIN)
    end_idx   = text.find(SENTINEL_END)
    if begin_idx == -1 or end_idx == -1:
        sys.exit(
            f"codegen-t3-strings: sentinels '{SENTINEL_BEGIN}' / '{SENTINEL_END}' "
            f"not found in {header_path}.\n"
            f"Add them after the closing '}} // namespace Lang' in lang_keys.h."
        )
    if end_idx <= begin_idx:
        sys.exit(f"codegen-t3-strings: sentinel order wrong in {header_path}.")

    # Content is everything on the line AFTER the begin sentinel to just before end sentinel.
    after_begin = text.index("\n", begin_idx) + 1
    new_text = (
        text[:after_begin]
        + new_section
        + "\n"
        + text[end_idx:]
    )
    if new_text == text:
        return False
    header_path.write_text(new_text, encoding="utf-8")
    return True


# ── Entry point ───────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(description="Type3 UI-string codegen")
    parser.add_argument("--in",   dest="yaml_in",   required=True,
                        help="Absolute path to teleproto3/spec/ux-strings.yaml")
    parser.add_argument("--out",  dest="header_out", required=True,
                        help="Absolute path to lang_keys.h (written in-place)")
    parser.add_argument("--stamp",dest="stamp",      required=True,
                        help="Stamp file path (written on success for CMake deps)")
    args = parser.parse_args()

    yaml_path   = Path(args.yaml_in)
    header_path = Path(args.header_out)
    stamp_path  = Path(args.stamp)

    if not yaml_path.exists():
        sys.exit(f"codegen-t3-strings: input not found: {yaml_path}")
    if not header_path.exists():
        sys.exit(f"codegen-t3-strings: output header not found: {header_path}")

    strings = parse_ux_strings(yaml_path)
    section = emit_section(strings)
    modified = patch_lang_keys(header_path, section)

    if modified:
        print(f"codegen-t3-strings: updated {header_path.name}")
    else:
        print(f"codegen-t3-strings: {header_path.name} already up-to-date")

    # Write stamp file regardless; CMake tracks deps via DEPENDS on ux-strings.yaml.
    stamp_path.parent.mkdir(parents=True, exist_ok=True)
    stamp_path.write_text("ok\n", encoding="utf-8")


if __name__ == "__main__":
    main()
